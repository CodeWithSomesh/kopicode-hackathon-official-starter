#!/usr/bin/env node
/**
 * One-off: fetch schools near every HomeLander (Gamuda Land) project from OpenStreetMap and write
 * src/lib/homelander/schools-data.ts.
 *
 *   node scripts/fetch-schools.mjs
 *
 * Data © OpenStreetMap contributors, ODbL (https://www.openstreetmap.org/copyright).
 * One Overpass request for amenity=school within RADIUS_M of each project; classified by name.
 * Keep PROJECTS in step with `townships` in src/lib/homelander/data.ts.
 */
import { writeFileSync } from "node:fs";

const RADIUS_M = 8000;
const CAP_PER_PROJECT = 40;
const OUT = "src/lib/homelander/schools-data.ts";

const PROJECTS = [
  ["cove", 2.8828, 101.6091],
  ["gardens", 3.2908, 101.5359],
  ["gardens-park", 3.3, 101.553],
  ["tf7", 2.9577, 101.5567],
  ["jade", 2.9972, 101.7541],
  ["kundang", 3.2882, 101.5083],
  ["haus15", 3.0756, 101.5919],
  ["horizon", 1.4576, 103.6456],
  ["bantayan", 5.973, 116.136],
  ["highpark", 3.1028, 101.5989],
  ["robertson", 3.1442, 101.7045],
  ["madge", 3.1579, 101.727],
  ["valencia", 3.2133, 101.5874],
  ["botanic", 2.9881, 101.4399],
  ["kemuning", 3.0049, 101.536],
];

/** @returns {"chinese_primary"|"tamil_primary"|"national_primary"|"secondary"|"international"|"private"} */
export function classify(name) {
  // Normalise "S.J.K (C)", "S.M.K." and the like before matching.
  const u = ` ${name} `.replace(/\./g, "").replace(/\s+/g, " ").replace(/\( /g, "(").replace(/ \)/g, ")").toUpperCase();
  if (/SJK ?\(C\)|SJKC|JENIS KEBANGSAAN ?\((C|CINA)\)/.test(u)) return "chinese_primary";
  if (/SJK ?\(T\)|SJKT|TAMIL|JENIS KEBANGSAAN ?\(T\)/.test(u)) return "tamil_primary";
  if (/INTERNATIONAL|ANTARABANGSA/.test(u)) return "international";
  if (/\bSMK|\bSMJK|\bSMKA|\bSBP\b|MENENGAH|SECONDARY|HIGH SCHOOL|BERASRAMA PENUH|TINGKATAN ENAM/.test(u)) return "secondary";
  if (/ SK |SEKOLAH KEBANGSAAN|SEKOLAH RENDAH KEBANGSAAN|NATIONAL SCHOOL/.test(u)) return "national_primary";
  return "private";
}

function km(aLat, aLng, bLat, bLng) {
  const r = Math.PI / 180;
  const h = Math.sin(((bLat - aLat) * r) / 2) ** 2 + Math.cos(aLat * r) * Math.cos(bLat * r) * Math.sin(((bLng - aLng) * r) / 2) ** 2;
  return 2 * 6371 * Math.asin(Math.sqrt(h));
}

const query = `[out:json][timeout:120];(${PROJECTS.map(([, lat, lng]) => `nwr["amenity"="school"](around:${RADIUS_M},${lat},${lng});`).join("")});out center tags;`;

const res = await fetch("https://overpass-api.de/api/interpreter", {
  method: "POST",
  headers: { "Content-Type": "application/x-www-form-urlencoded", "User-Agent": "HomeLander-hackathon/1.0 (one-off school fetch)" },
  body: "data=" + encodeURIComponent(query),
});
if (!res.ok) throw new Error(`Overpass ${res.status}: ${await res.text()}`);
const json = await res.json();

const seen = new Map();
for (const el of json.elements) {
  const name = (el.tags?.name ?? el.tags?.["name:ms"] ?? el.tags?.["name:en"] ?? "").trim();
  const lat = el.lat ?? el.center?.lat;
  const lng = el.lon ?? el.center?.lon;
  if (!name || lat == null || lng == null) continue;
  // Skip tuition/kindergarten-ish entries that are tagged as schools.
  if (/tadika|kinderg[a-z]*|tuition|tuisy?en|taska|nursery|pre-?school|playschool|driving|memandu|cookery|swimming|training|institut|college|kolej vokasional|university|universiti|akademi seni|bengkel|kem bina|^hall$|adtec|permata|pasti /i.test(name)) continue;
  const key = name.toLowerCase().replace(/[^a-z0-9]/g, "");
  const prev = seen.get(key);
  // Dedupe the same school mapped twice (node + building) when they sit within 1 km.
  if (prev && km(prev.lat, prev.lng, lat, lng) < 1) continue;
  seen.set(prev ? `${key}@${lat.toFixed(3)}` : key, { name, type: classify(name), lat: +lat.toFixed(5), lng: +lng.toFixed(5) });
}
const all = [...seen.values()];

// Cap per project: keep the nearest CAP_PER_PROJECT, but always keep the nearest of each type.
const keep = new Set();
const report = [];
for (const [id, lat, lng] of PROJECTS) {
  const near = all
    .map((s) => ({ s, d: km(lat, lng, s.lat, s.lng) }))
    .filter((x) => x.d <= RADIUS_M / 1000)
    .sort((a, b) => a.d - b.d);
  const picked = new Set(near.slice(0, CAP_PER_PROJECT).map((x) => x.s));
  const types = new Set();
  for (const x of near) if (!types.has(x.s.type)) { types.add(x.s.type); picked.add(x.s); }
  picked.forEach((s) => keep.add(s));
  const counts = {};
  for (const s of picked) counts[s.type] = (counts[s.type] ?? 0) + 1;
  report.push([id, near.length, picked.size, counts]);
}

const rows = [...keep].sort((a, b) => a.name.localeCompare(b.name));
const body = `/**
 * Schools near HomeLander's Gamuda Land projects, generated by scripts/fetch-schools.mjs
 * (${new Date().toISOString().slice(0, 10)}). Do not edit by hand; re-run the script.
 *
 * Source: OpenStreetMap, amenity=school within ${RADIUS_M / 1000} km of each project, nearest ${CAP_PER_PROJECT}
 * per project (plus the nearest of each type). Type is guessed from the name.
 * © OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright).
 * Coverage is good in the Klang Valley but not complete.
 */

export type SchoolRow = {
  name: string;
  type: "national_primary" | "chinese_primary" | "tamil_primary" | "secondary" | "international" | "private";
  lat: number;
  lng: number;
};

export const schoolRows: SchoolRow[] = [
${rows.map((s) => `  { name: ${JSON.stringify(s.name)}, type: "${s.type}", lat: ${s.lat}, lng: ${s.lng} },`).join("\n")}
];
`;
writeFileSync(OUT, body);
console.log(`wrote ${rows.length} schools to ${OUT}`);
for (const [id, within, kept, counts] of report) console.log(id.padEnd(13), `within=${within}`.padEnd(11), `kept=${kept}`.padEnd(8), JSON.stringify(counts));
